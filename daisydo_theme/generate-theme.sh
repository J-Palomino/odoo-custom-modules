echo "Hover:        $THEME_HOVER"
echo "Active:       $THEME_ACTIVE"
echo "Accent:       $THEME_ACCENT"
echo "BG:           $THEME_BG"
echo "Text:         $THEME_TEXT (luminance=$LUM)"
echo "Primary RGB:  $THEME_PRIMARY_RGB"
echo ""

