# ============================================================
# HELPER FUNCTIONS
# ============================================================

hex_to_rgb() {
  local hex="${1#\#}"
  local r=$((16#${hex:0:2}))
  local g=$((16#${hex:2:2}))
  local b=$((16#${hex:4:2}))
  echo "$r, $g, $b"
}

hex_to_r() { local hex="${1#\#}"; echo $((16#${hex:0:2})); }
hex_to_g() { local hex="${1#\#}"; echo $((16#${hex:2:2})); }
hex_to_b() { local hex="${1#\#}"; echo $((16#${hex:4:2})); }

# Compute relative luminance (0-255 scale approximation)
luminance() {
  local r=$(hex_to_r "$1")
  local g=$(hex_to_g "$1")
  local b=$(hex_to_b "$1")
  echo $(( (r * 299 + g * 587 + b * 114) / 1000 ))
}

# Darken a hex color by a percentage (0-100)
darken() {
  local hex="${1#\#}"
  local pct=$2
  local factor=$(( 100 - pct ))
  local r=$(( (16#${hex:0:2}) * factor / 100 ))
  local g=$(( (16#${hex:2:2}) * factor / 100 ))
  local b=$(( (16#${hex:4:2}) * factor / 100 ))
  printf "#%02x%02x%02x" "$r" "$g" "$b"
}

# Lighten a hex color toward white by a percentage (0-100)
lighten() {
  local hex="${1#\#}"
  local pct=$2
  local r=$(( (16#${hex:0:2}) + (255 - (16#${hex:0:2})) * pct / 100 ))
  local g=$(( (16#${hex:2:2}) + (255 - (16#${hex:2:2})) * pct / 100 ))
  local b=$(( (16#${hex:4:2}) + (255 - (16#${hex:4:2})) * pct / 100 ))
  printf "#%02x%02x%02x" "$r" "$g" "$b"
}

# ============================================================
# READ ENV VARS WITH DEFAULTS
# ============================================================

THEME_PRIMARY="${ODOO_BRAND_PRIMARY:-#00954c}"
THEME_ACCENT="${ODOO_BRAND_ACCENT:-#dac554}"

# Auto-derive hover/active/bg if not explicitly set
THEME_HOVER="${ODOO_BRAND_HOVER:-$(darken "$THEME_PRIMARY" 15)}"
THEME_ACTIVE="${ODOO_BRAND_ACTIVE:-$(darken "$THEME_PRIMARY" 30)}"
THEME_BG="${ODOO_BRAND_BG:-$(lighten "$THEME_PRIMARY" 90)}"

# Compute text-on-primary based on luminance
LUM=$(luminance "$THEME_PRIMARY")
if [ "$LUM" -gt 160 ]; then
  THEME_TEXT="#1a1a1a"
  THEME_TEXT_HOVER="#000000"
  THEME_TEXT_ALPHA="rgba(26, 26, 26, 0.9)"
else
  THEME_TEXT="#ffffff"
  THEME_TEXT_HOVER="#ffffff"
  THEME_TEXT_ALPHA="rgba(255, 255, 255, 0.9)"
fi

THEME_PRIMARY_RGB=$(hex_to_rgb "$THEME_PRIMARY")
THEME_ACCENT_RGB=$(hex_to_rgb "$THEME_ACCENT")

# ============================================================
# DISPLAY CONFIGURATION
# ============================================================

echo "============================================================"
echo "DaisyDo Theme Generator"
echo "============================================================"
echo ""
