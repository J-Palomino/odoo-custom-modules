#!/bin/bash
# ============================================================
# DaisyDo Theme Generator
# ============================================================
# Generates SCSS files with custom colors from env vars.
# Called by fix-config.sh at container startup.
#
# Environment Variables:
#   ODOO_BRAND_PRIMARY   - Primary brand color (default: #00954c)
#   ODOO_BRAND_HOVER     - Hover state color (auto-derived if unset)
#   ODOO_BRAND_ACTIVE    - Active/pressed state color (auto-derived)
#   ODOO_BRAND_ACCENT    - Accent/secondary color (default: #dac554)
#   ODOO_BRAND_BG        - Light background color (auto-derived)
# ============================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PRIMARY_VARS_FILE="$SCRIPT_DIR/static/src/scss/primary_variables.scss"
THEME_FILE="$SCRIPT_DIR/static/src/scss/theme.scss"
